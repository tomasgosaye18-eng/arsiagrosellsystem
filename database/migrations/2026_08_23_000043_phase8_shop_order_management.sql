USE `aam_db`;
SET FOREIGN_KEY_CHECKS = 0;

-- =========================================================
-- 1. PICKUP CODE — for order verification at pickup desk
--    A short, human-readable code shown to the customer on
--    the order confirmation page.
--    Salesperson can search by this code using the
--    /api/customer/shop-orders/search endpoint.
--    Generated by application layer at order creation time.
-- =========================================================
ALTER TABLE `customer_orders`
    ADD COLUMN IF NOT EXISTS `pickup_code`
        VARCHAR(10) NULL DEFAULT NULL
        COMMENT '6-char uppercase alphanumeric pickup verification code shown to customer'
        AFTER `order_reference`;

-- Index for pickup code lookup (used in AJAX search)
CREATE INDEX IF NOT EXISTS `idx_co_pickup_code`
    ON `customer_orders`(`pickup_code`);

-- =========================================================
-- 2. ITEM COUNT CACHE — denormalized count for queue display
--    Avoids subquery on every queue page load.
--    Updated by application layer when order is created.
-- =========================================================
ALTER TABLE `customer_orders`
    ADD COLUMN IF NOT EXISTS `item_count`
        SMALLINT UNSIGNED NOT NULL DEFAULT 0
        COMMENT 'Cached count of distinct products in this order (set at creation)'
        AFTER `total_amount`;

-- =========================================================
-- 3. DATE FILTER INDEX — for date-range filtering in queue
-- =========================================================
CREATE INDEX IF NOT EXISTS `idx_co_created_date`
    ON `customer_orders`(`shop_id`, `created_at`);

-- =========================================================
-- 4. ENSURE CUSTOMER_ORDER_STATUS_CHANGES INDEXES
-- =========================================================
CREATE INDEX IF NOT EXISTS `idx_cosc_order_id`   ON `customer_order_status_changes`(`order_id`);
CREATE INDEX IF NOT EXISTS `idx_cosc_shop_id`    ON `customer_order_status_changes`(`shop_id`);
CREATE INDEX IF NOT EXISTS `idx_cosc_changed_by` ON `customer_order_status_changes`(`changed_by`);
CREATE INDEX IF NOT EXISTS `idx_cosc_changed_at` ON `customer_order_status_changes`(`changed_at` DESC);

